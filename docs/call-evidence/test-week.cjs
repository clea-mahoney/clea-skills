'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const EvidenceWeek = require('./week-engine.js');
const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const data = JSON.parse(html.match(/<script type="application\/json" id="presentation-data">([\s\S]*?)<\/script>/)[1]);
const memory = new Map();
const storage = { getItem: key => memory.get(key) || null, setItem: (key, value) => memory.set(key, value) };
const week = new EvidenceWeek(data, storage);
assert(week.validate());
assert.equal(week.themes().length, 21);
assert.throws(() => week.review('approval', 'merge-2'));
week.run();
week.run();
let verification = week.themes().find(row => row.id === 2);
assert.equal(verification.evidence.length, 4);
assert.equal(new Set(verification.evidence.map(e => e.speaker)).size, 3);
assert(verification.evidence.some(e => e.speaker === 'Tom Becker' && e.company === 'Company not stated'));
assert(!week.themes().some(row => row.evidence.some(e => ['Dana Kim', 'Sam'].includes(e.speaker))));
week.review('approval', 'subset-2');
week.review('bounded', 'merge-7');
assert.equal(week.themes().length, 21);
verification = week.themes().find(row => row.id === 2);
assert.equal(verification.evidence.length, 6);
assert.equal(verification.subthemes.length, 1);
assert.equal(week.themes().find(row => row.id === 7).evidence.length, 1);
assert.equal(new EvidenceWeek(data, storage).themes().find(row => row.id === 2).subthemes.length, 1);
week.review('approval', 'merge-13');
assert.equal(week.themes().find(row => row.id === 2).evidence.length, 4);
assert.equal(week.themes().find(row => row.id === 13).evidence.length, 2);
week.review('approval', 'new');
assert.equal(week.themes().length, 22);
assert.throws(() => week.review('sam', 'internal', ''));
assert.throws(() => week.review('timeout', 'bug', ''));
week.review('sam', 'unconfirmed');
assert.equal(week.pending(), 1);
assert.equal(week.themes().find(row => row.id === 15).recovered_route, 'hold');
const corrupted = structuredClone(data.analysis);
corrupted.themes[0].evidence[0].quote = 'This quote was invented.';
assert.throws(() => week.validate(corrupted));
week.reviewHistorical(15, 'hold', 'Keep this historical review through a restart.');
week.reset();
assert.equal(week.state.ran, false);
assert.equal(week.state.historicalReviews[15].route, 'hold');
const app = fs.readFileSync(path.join(__dirname, 'app.js'), 'utf8');
const css = fs.readFileSync(path.join(__dirname, 'styles.css'), 'utf8');
assert(!app.includes('fetch('));
assert(!css.includes('text-transform:uppercase'));
assert(html.includes('<h1>Customer Calls to Education Decisions</h1>'));
assert(!html.includes('review choices stay in this browser'));
console.log('Passed: source integrity, repeat runs, speaker counting, theme merging, subthemes, independent themes, human verification gates, saved reviews, historical preservation, and presentation regressions.');

// Export correctness: actual source evidence, regular CSV rows, no invented historical dates.
const labels = {education:'Education priority',unknown:'Open to explore',hold:'Deliberate Hold',product:'Product first',docs:'Documentation first'};
const exported = new EvidenceWeek(data, null);
let records = exported.exportRecords(labels);
const columns = records[0], col = name => columns.indexOf(name);
assert(!columns.some(x => ['Row','Basis','Saved note','Clea review note'].includes(x)));
assert(records.every(row => row.length === columns.length));
for (const row of records.slice(1)) {
  assert.equal(row[col('Data type')], 'Fictional demonstration');
  if (!row[col('Transcript excerpt')]) { assert.equal(row[col('Call date')], ''); continue; }
  const call = row[col('Source transcript')].replace('.txt','.md');
  const source = exported.lines().get(call + '|' + row[col('Transcript timestamp')]);
  assert(source);
  assert.equal(source.quote, row[col('Transcript excerpt')]);
  assert.equal(source.speaker, row[col('Speaker')]);
  assert(fs.existsSync(path.join(__dirname, row[col('Source transcript')])));
}
exported.run(); exported.review('bounded', 'merge-7', '=HYPERLINK("bad")');
records = exported.exportRecords(labels);
const merged = records.find(row => row[col('Theme')] === 'Starting with one small automation' && row[col('Speaker')] === 'Lena Fischer');
assert(merged); assert.equal(merged[col('Review status')], 'Reviewed in walkthrough');
assert(!records.some(row => row[col('Status')] === 'Proposed theme' && row[col('Speaker')] === 'Lena Fischer' && row[col('Transcript excerpt')].includes('automate everything')));
assert(exported.exportCSV(labels).includes("'=HYPERLINK"));
assert.equal(data.historical.rows.filter(x=>x.sample_route==='education').length,2);
assert.equal(data.historical.rows.filter(x=>x.recovered_route==='unknown').length,15);
console.log('Passed: CSV source attribution, uniform columns, empty unsupported call fields, decisions, formula escaping, and separation of sample priorities from historical outcomes.');

assert.equal(exported.handoffQuestions().length,4);
assert.equal(exported.handoffText().match(/^\d\. /gm).length,4);
assert(exported.handoffText().includes('2 calls reviewed, 4 questions'));
assert(exported.handoffQuestions().every(q=>q.evidence.every(e=>e && e.quote && e.timestamp)));
exported.state.reviews.tom = {choice:'retain'};
assert.equal(exported.pending(),3); // An old company review cannot reduce the four-question count.
console.log('Passed: four-question alert, source-linked copy text, and legacy review counting.');

// A merged theme must not attach the approval decision to its routine evidence.
const mixed = new EvidenceWeek(data, null);
mixed.run(); mixed.review('approval', 'merge-2', 'Keep the evidence together.');
const mixedRows = mixed.exportRecords(labels).filter(row => row[col('Theme')] === 'Checking AI-built workflows');
assert.equal(mixedRows.filter(row => row[col('Decision')]).length, 2);
assert.equal(mixedRows.filter(row => row[col('Review status')] === 'Evidence linked').length, 4);
assert.equal(mixed.themes().find(row => row.id === 2).next_action, data.historical.rows.find(row => row.id === 2).next_action);
console.log('Passed: per-quote review attribution and unchanged example next actions after a merge.');

// Responses are not resolutions, and identity and product decisions stay separate.
const follow = new EvidenceWeek(data, storage);
follow.reset(); follow.run();
follow.review('bounded', 'merge-7');
follow.review('approval', 'subset-2');
follow.review('sam', 'unconfirmed', 'Check attendee identity.');
follow.review('timeout', 'investigate', 'Ask which connector.');
assert.equal(follow.recorded(), 4);
assert(follow.followUps().some(q => q.id === 'sam'));
assert(follow.followUps().some(q => q.id === 'timeout'));
assert.equal(follow.affectedTheme('bounded'), 7);
assert.equal(follow.affectedTheme('approval'), 2);
const fullExport = follow.exportRecords(labels);
const identityRow = fullExport.find(r => r[col('Theme')] === 'Sam’s identity review');
const timeoutRow = fullExport.find(r => r[col('Theme')].includes('one-hour connector'));
assert.equal(identityRow[col('Decision note')], 'Check attendee identity.');
assert.equal(timeoutRow[col('Decision note')], 'Ask which connector.');
assert(identityRow[col('Review status')].includes('follow-up'));
assert(timeoutRow[col('Review status')].includes('follow-up'));
assert(follow.handoffText().includes('4 decisions recorded'));
assert(follow.handoffText().includes('Ask product to investigate the timeout'));
assert(follow.handoffText().includes('Product investigation pending'));
follow.saveDraft('timeout', 'bug', 'Unsaved verification note');
const restored = new EvidenceWeek(data, storage);
assert.deepEqual(restored.state.drafts.timeout, { choice: 'investigate', note: 'Unsaved verification note' });
assert.equal(restored.state.reviews.timeout.choice, 'investigate');
restored.review('timeout', 'investigate');
assert(!restored.state.drafts.timeout);
restored.review('sam', 'unconfirmed');
assert.equal(restored.followUp('sam'), 'Confirm Sam’s identity; exclude from customer counts');
restored.review('bounded', 'new');
assert.equal(restored.affectedTheme('bounded'), 23);
assert.equal(restored.themes().find(r => r.id === 23).evidence[0].speaker, 'Lena Fischer');
assert.match(restored.themes().find(r => r.id === 23).next_action, /distinct audience or learning objective/);
assert.match(restored.themes().find(r => r.id === 23).handling, /Separate theme recorded/);
assert.equal(restored.themes().find(r => r.id === 7).evidence.length, 0);
restored.reset();
assert.deepEqual(restored.state.drafts, {});
assert.equal(restored.recorded(), 0);
console.log('Passed: unresolved follow-ups, separate identity export, current copied handoff, saved drafts, and changed theme destinations.');

for (const choice of ['expected', 'bug']) assert.throws(() => restored.review('timeout', choice, 'hi'));
assert.throws(() => restored.review('sam', 'internal', 'hi'));
const legacyState = {version: 4, ran: true, reviews: {sam: {choice: 'internal', note: 'hi'}, timeout: {choice: 'expected', note: 'hi'}}, historicalReviews: {}};
const migrated = new EvidenceWeek(data, {getItem: () => JSON.stringify(legacyState)});
assert.equal(migrated.state.reviews.sam.choice, 'unconfirmed');
assert.equal(migrated.state.reviews.timeout.choice, 'investigate');
assert.equal(migrated.state.reviews.timeout.note, 'hi');
const named = new EvidenceWeek(data, storage);
named.run();
for (const [id, themeId] of [['bounded', 23], ['approval', 22]]) {
  named.saveDraft(id, 'new', 'A comment', 'hi');
  assert.equal(new EvidenceWeek(data, storage).state.drafts[id].themeName, 'hi');
  named.review(id, 'new', 'A comment', ' hi ');
  assert.equal(named.themes().find(r => r.id === themeId).title, 'hi');
  assert.equal(new EvidenceWeek(data, storage).state.reviews[id].themeName, 'hi');
  assert(named.exportRecords({}).some(row => row[0] === 'hi'));
  assert.throws(() => named.review(id, 'new', '', '   '));
  assert.throws(() => named.review(id, 'new', '', 'x'.repeat(121)));
}
console.log('Passed: custom theme names, saved drafts, reloads, CSV export, and name validation.');
